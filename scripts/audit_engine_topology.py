#!/usr/bin/env python3
"""Render a static inventory joining canonical topology, lifecycle resolvers, and Director discovery.

This is a source inventory only. It does not boot services or claim runtime health.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

# Make `python scripts/audit_engine_topology.py` work from any working directory.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from core.engine_topology import CANONICAL_ENGINE_DEPENDENCIES
from core.service_definitions import SERVICE_DEFINITIONS
from services.director.analysis import ENGINE_REGISTRY


CANONICAL_ALIASES = {"meta_director": "director"}
INFRASTRUCTURE_NODES = {"redis", "supabase", "gemini", "github"}
BOOT_OWNERS = {
    "supabase": ("SupabaseClient", "all modes; may be skipped by settings"),
    "event_bus": ("EventBus", "all modes"),
    "redis": ("RedisClient", "all modes; may be skipped by settings"),
    "task_queue": ("TaskQueue", "full/api/core/workers/director/meta/condition"),
    "plugin_registry": ("PluginRegistry", "full/api/core/workers/director/meta/condition"),
    "job_service": ("JobService", "full/api/core/workers/director/meta/condition"),
    "job_stats_service": ("JobStatsService", "full/api/core/workers/director/meta/condition"),
    "render_queue": ("RenderQueue", "full/api/core/workers/director/meta/condition"),
    "meta_engine": ("MetaEngine", "full/core/meta"),
    "director": ("Director", "full/core/director"),
    "condition_engine": ("ConditionEngine", "full/core/condition"),
    "ai_orchestrator": ("AIOrchestrator", "full/core"),
    "content_engine": ("ContentEngine", "full/core"),
    "autonomous_content": ("AutonomousContent", "full/core"),
    "autonomous_loop": ("AutonomousLoop", "full/core"),
    "brand_scheduler": ("BrandSchedulers", "full/workers"),
    "scheduler": ("BrandSchedulers / BrandSchedulerManager", "full/workers"),
    "health_monitor": ("HealthMonitor", "full/api"),
    "enterprise_emitters": ("EnterpriseEmitters", "full/api"),
    "github": ("GitHubConnector", "full/github"),
}


def build_engine_inventory() -> list[dict[str, Any]]:
    resolvers = {name: resolver.__name__ for name, resolver, _critical in SERVICE_DEFINITIONS}
    criticality = {name: critical for name, _resolver, critical in SERVICE_DEFINITIONS}
    director: dict[str, list[str]] = {}
    for module_path, attr_name, display_name, sector in ENGINE_REGISTRY:
        name = CANONICAL_ALIASES.get(display_name, display_name)
        director.setdefault(name, []).append(
            f"{module_path}.{attr_name} [{getattr(sector, 'value', sector)}]"
        )

    rows = []
    for name, dependencies in CANONICAL_ENGINE_DEPENDENCIES.items():
        boot_step, modes = BOOT_OWNERS.get(name, ("not mapped to a named boot step", "verify selected mode/owner"))
        if name in resolvers:
            ownership = f"service definition: {resolvers[name]}"
            critical = "critical" if criticality[name] else "optional"
        elif name in INFRASTRUCTURE_NODES:
            ownership = "infrastructure/provider node; no direct service resolver"
            critical = "n/a"
        else:
            ownership = "no direct service definition; boot owner or dynamic runtime must supply instance"
            critical = "n/a"
        rows.append({
            "engine": name,
            "dependencies": list(dependencies),
            "service_registry": ownership,
            "criticality": critical,
            "director_discovery": "; ".join(director.get(name, [])) or "not directly listed",
            "boot_step": boot_step,
            "service_modes": modes,
        })
    return rows


def render_markdown(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# Kanyoza Engine Runtime Map (source inventory)",
        "",
        "Generated by `scripts/audit_engine_topology.py` from the canonical topology, service definitions, and Director discovery registry.",
        "",
        "> This is a source-level ownership map, not a live health report. Runtime presence and health must be confirmed using `/api/v1/topology` and `/api/v1/system-health` after startup.",
        "",
        f"Canonical nodes: **{len(rows)}**.",
        "",
        "| Engine | Declared dependencies | Service registry | Director discovery export | Boot owner / modes |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        dependencies = ", ".join(f"`{name}`" for name in row["dependencies"]) or "—"
        director = row["director_discovery"].replace("|", "\\|")
        service = f"{row['service_registry']} ({row['criticality']})".replace("|", "\\|")
        boot = f"{row['boot_step']} — {row['service_modes']}".replace("|", "\\|")
        lines.append(f"| `{row['engine']}` | {dependencies} | {service} | {director} | {boot} |")
    lines += [
        "",
        "## Reading the map",
        "",
        "- **Declared dependencies** come only from `core/engine_topology.py`; dependency direction is engine → dependency/provider.",
        "- **Service registry** tells whether a service definition exists and whether it is marked critical. Optional services may be skipped if the owner lifecycle has not initialized them.",
        "- **Director discovery export** shows the configured module/export and sector label. A class export is discoverable only if the container already holds a live instance; arbitrary callables are not invoked.",
        "- **Boot owner / modes** is a source map of the selected boot sequence. Mode selection, configuration, and successful startup determine actual presence.",
        "- `not directly listed` or `no direct service definition` means the static registries do not directly establish runtime presence; it does not mean the component is broken.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write Markdown to this path instead of stdout")
    args = parser.parse_args()
    rendered = render_markdown(build_engine_inventory())
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered + "\n", encoding="utf-8")
    else:
        print(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
